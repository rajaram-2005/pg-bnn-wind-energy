PROVENANCE_BY_ID: dict[str, Concept] = {c.concept_id: c for c in PROVENANCE}

REUSE_KINDS = ("concept", "equation", "schema", "protocol")


def provenance_table() -> str:
    """Markdown table of every declared reused concept."""
    header = (
        "| Concept | Source repository | Upstream path | Licence | Reuse | Local path | Validated by |\n"
        "|---|---|---|---|---|---|---|"
    )
    return "\n".join([header, *[c.as_row() for c in PROVENANCE]])


def provenance_markdown() -> str:
    """Full provenance document body (used to generate docs/PROVENANCE.md)."""
    counts: dict[str, int] = {}
    for c in PROVENANCE:
        counts[c.reuse] = counts.get(c.reuse, 0) + 1
    by_repo: dict[str, int] = {}
    for c in PROVENANCE:
        by_repo[c.source_repo] = by_repo.get(c.source_repo, 0) + 1
    summary = "\n".join(f"- **{repo}** — {n} reused concepts" for repo, n in sorted(by_repo.items()))
    kinds = "\n".join(f"- `{k}` — {counts.get(k, 0)}" for k in REUSE_KINDS)
    unvalidated = [c.concept_id for c in PROVENANCE if not c.validated_by]
    gap = (
        "Every declared concept is covered by at least one test."
        if not unvalidated
        else "Declared but not yet covered by a test: " + ", ".join(unvalidated)
    )
    return (
        "# Provenance registry\n\n"
        "Generated by `python -m windfusion provenance --markdown`. Do not edit "
        "by hand; edit `windfusion/provenance.py` instead.\n\n"
        "No upstream source tree was copied into this repository. `concept` "
        "entries were re-implemented after reading the upstream code; `equation` "
        "entries are published physical relations that predate the upstream "
        "repositories.\n\n"
        f"## Sources\n\n{summary}\n\n## Reuse kinds\n\n{kinds}\n\n"
        f"## Registry\n\n{provenance_table()}\n\n## Validation gap\n\n{gap}\n"
    )


def validate_provenance() -> list[str]:
    """Return a list of problems (empty list means the registry is consistent)."""
    problems = []
    seen = set()
    for c in PROVENANCE:
        if c.concept_id in seen:
            problems.append(f"duplicate concept id {c.concept_id}")
        seen.add(c.concept_id)
        if c.reuse not in REUSE_KINDS:
            problems.append(f"{c.concept_id}: unknown reuse kind {c.reuse!r}")
        if not c.source_repo:
            problems.append(f"{c.concept_id}: missing source repository")
        if not c.local_path:
            problems.append(f"{c.concept_id}: missing local path")
    return problems
