"""Machine-readable provenance registry for WindFusion v0.2.

Every concept that WindFusion reuses from an upstream repository owned by
``rajaram-2005`` is declared here with its upstream path, upstream licence and
the *kind* of reuse.  Nothing in this repository is copied verbatim from an
upstream tree: entries marked ``concept`` were re-implemented from first
principles after reading the upstream source, and entries marked ``equation``
re-derive published physical relations that predate (and are not owned by) any
of the upstream repositories.

The registry is consumed by:

* ``windfusion provenance`` (CLI) and :func:`provenance_table`,
* ``docs/PROVENANCE.md`` (generated by ``python -m windfusion provenance --markdown``),
* the audit test ``tests/test_provenance.py``, which fails if a module claims a
  lineage it does not declare.

Reuse kinds
-----------
``concept``   Idea/strategy re-implemented independently in this repository.
``equation``  Published physical relation (Heier Cp, ISO 281, Jensen wake, ...)
              re-derived here; upstream only supplied the choice of relation.
``schema``    Naming/structural convention adopted for interoperability.
``protocol``  Evaluation or training protocol reproduced so numbers are
              comparable across the repositories.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Concept:
    """One reused idea and where it came from."""

    concept_id: str
    source_repo: str
    upstream_path: str
    upstream_license: str
    reuse: str
    local_path: str
    description: str
    validated_by: tuple[str, ...] = field(default_factory=tuple)
    notes: str = ""

    def as_row(self) -> str:
        validated = ", ".join(self.validated_by) if self.validated_by else "not yet validated"
        return (
            f"| `{self.concept_id}` | {self.source_repo} | `{self.upstream_path}` | "
            f"{self.upstream_license} | {self.reuse} | `{self.local_path}` | {validated} |"
        )


